def calculate_academic_status(cgpa: float, attendance: float) -> str:
    """Calculate status from thresholds."""
    if cgpa >= 9.0 and attendance >= 85.0:
        return "Dean's List"
    if cgpa < 5.5 or attendance < 65.0:
        return "Academic Warning"
    if cgpa < 6.5 or attendance < 75.0:
        return "Needs Support"
    return "Good Standing"
